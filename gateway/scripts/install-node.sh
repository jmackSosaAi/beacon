#!/bin/zsh
# Installs the Beacon Mac node as a LaunchAgent (runs at login, restarts if it stops).
# Needs ~/.config/jarvis/node_token (already created). No typed input.
set -euo pipefail
GW="$(cd "$(dirname "$0")/.." && pwd)"
NODE="$(command -v node)"; PLIST="$HOME/Library/LaunchAgents/com.jarvis.node.plist"; LOG="$HOME/Library/Logs/jarvis-node.log"
security find-generic-password -s jarvis-node -a beacon -w >/dev/null 2>&1 || [[ -s "$HOME/.config/jarvis/node_token" ]] || { echo "No node token (Keychain item jarvis-node or ~/.config/jarvis/node_token)"; exit 1; }
[[ -x /Users/you/.local/bin/claude ]] || { echo "Claude Code not found at ~/.local/bin/claude"; exit 1; }
[[ -f "$HOME/.config/jarvis/node_token" ]] && chmod 600 "$HOME/.config/jarvis/node_token"
mkdir -p "$HOME/Library/LaunchAgents" "$HOME/Library/Logs"
# Generated by agent-node/lib.mjs so the daily integrity check can compare it exactly.
"$NODE" --input-type=module -e "import {plistFor} from '$GW/agent-node/lib.mjs';process.stdout.write(plistFor({node:'$NODE',gw:'$GW',home:process.env.HOME}))" > "$PLIST"
launchctl bootout "gui/$(id -u)/com.jarvis.node" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
echo "Beacon node installed. Log: $LOG  (Telegram /node shows it online within a minute.)"
